export class ApiError extends Error {
  constructor(public code: string, public status = 0) { super(code); }
}
export function errorMessage(e: unknown): string {
  const code = e instanceof ApiError ? e.code : e instanceof Error && ERRORS[e.message] ? e.message : "internal_error";
  if (code.startsWith("missing_") || code.startsWith("invalid_")) return ERRORS[code] ?? "بيانات غير صالحة، راجع الحقول";
  if (code === "app_base_url_not_configured") return "إعدادات الدفع غير مكتملة على الخادم";
  return ERRORS[code] ?? ERRORS.internal_error;
}
